"""Generate DL-Learner .conf files, run them, and evaluate learned concepts.

For every (experiment setting, dataset, fold) we
  1. write conf/<setting>/<dataset>/fold<k>.conf  (training examples only)
  2. run DL-Learner (tools/dlcli.sh), raw output -> results/runs/...
  3. take the best concept (solution #1), classify the held-out test trains
     with dl_concepts.ClosedWorldModel, and store one CSV row.
Additionally a "full" run on all examples gives the concept reported in the
paper for each (setting, dataset).

Usage:
  python src/run_experiments.py                 # all settings
  python src/run_experiments.py celoe_alc eltl  # selected settings
  python src/run_experiments.py --jobs 4
"""
from __future__ import annotations

import argparse
import csv
import os
import re
import subprocess
import sys
import time
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from dl_concepts import ClosedWorldModel, depth, length, parse, to_dl  # noqa: E402
from splits import DATASETS, load_dataset, load_splits  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
CONF = ROOT / "conf"
RUNS = ROOT / "results" / "runs"
RESULTS = ROOT / "results"
DLCLI = ROOT / "tools" / "dlcli.sh"
PREFIX = "http://example.org/trains#"

# ---------------------------------------------------------------------------
# Experiment settings.  Each one changes ONE thing w.r.t. the reference
# setting "celoe_alc" (CELOE, closed-world reasoner, full rho operator, 5 s).
# ---------------------------------------------------------------------------
BASE = {"alg": "celoe", "time": 5, "reasoner": "cwr", "ontology": "open",
        "op": {}, "alg_opts": {}, "datasets": DATASETS}
SMALL = ["michalski10", "michie24"]  # HermiT (OWA) is too slow for 1600 individuals

SETTINGS: dict[str, dict] = {
    # -- reference
    "celoe_alc": {},
    # -- hypothesis language
    "celoe_no_neg_all": {"op": {"useNegation": "false", "useAllConstructor": "false"}},
    "celoe_no_data_card": {"op": {"useNumericDatatypes": "false",
                                  "useCardinalityRestrictions": "false"}},
    "eltl_el": {"alg": "eltl"},
    # -- search strategy / heuristic
    "ocel_alc": {"alg": "ocel"},
    # -- runtime budget
    "celoe_t1": {"time": 1},
    "celoe_t20": {"time": 20},
    # -- noise tolerance
    "celoe_noise10": {"alg_opts": {"noisePercentage": "10"}},
    # -- open vs closed world
    "owa_hermit_open": {"reasoner": "owa", "ontology": "open", "datasets": SMALL},
    "owa_hermit_closed": {"reasoner": "owa", "ontology": "closed", "datasets": SMALL},
}


def setting(name: str) -> dict:
    s = {**BASE, **SETTINGS[name]}
    s["name"] = name
    return s


def ontology_for(dataset: str, s: dict) -> Path:
    base = dataset.replace("_noise10", "")  # noisy set shares the ABox
    suffix = "_closed" if s["ontology"] == "closed" else ""
    return ROOT / "ontology" / f"{base}{suffix}.owl"


# ---------------------------------------------------------------------------
# .conf generation
# ---------------------------------------------------------------------------
def make_conf(s: dict, dataset: str, pos: list[str], neg: list[str], conf_path: Path) -> str:
    owl = os.path.relpath(ontology_for(dataset, s), conf_path.parent)
    ex = lambda ids: ", ".join(f'"ex:{i}"' for i in ids)
    lines = [
        f"// setting={s['name']} dataset={dataset} -- generated by src/run_experiments.py",
        'prefixes = [ ("ex","http://example.org/trains#") ]',
        'ks.type = "OWL File"',
        f'ks.fileName = "{owl}"',
    ]
    if s["reasoner"] == "cwr":
        lines += ['reasoner.type = "closed world reasoner"']
    else:
        lines += ['reasoner.type = "OWL API Reasoner"',
                  'reasoner.reasonerImplementation = "hermit"']
    lines += [
        "reasoner.sources = { ks }",
        'lp.type = "posNegStandard"',
        f"lp.positiveExamples = {{ {ex(pos)} }}",
        f"lp.negativeExamples = {{ {ex(neg)} }}",
        f'alg.type = "{s["alg"]}"',
        f"alg.maxExecutionTimeInSeconds = {s['time']}",
    ]
    if s["alg"] == "celoe":
        lines += ['alg.searchTreeFile = "log/searchTree.txt"']
    for k, v in s["alg_opts"].items():
        lines.append(f"alg.{k} = {v}")
    if s["op"] and s["alg"] in ("celoe", "ocel"):
        lines += ['op.type = "rho"', "op.reasoner = reasoner"]
        lines += [f"op.{k} = {v}" for k, v in s["op"].items()]
        lines.append("alg.operator = op")
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------------------
# Output parsing
# ---------------------------------------------------------------------------
SOL_RE = re.compile(r"^\s*1:\s*(.+?)\s*\((?:pred\. acc\.|accuracy)[^()]*\)\s*$", re.M)
TESTED_RE = re.compile(r"(\d+) descriptions tested")


def parse_output(out: str) -> dict:
    i = out.rfind("solutions")
    m = SOL_RE.search(out, i if i >= 0 else 0)
    concept = m.group(1).replace("ex:", "").replace("<" + PREFIX, "").replace(">", "") if m else None
    tested = TESTED_RE.findall(out)
    return {"concept": concept, "tested": int(tested[-1]) if tested else None}


# ---------------------------------------------------------------------------
# Running
# ---------------------------------------------------------------------------
_models: dict[str, ClosedWorldModel] = {}


def model_for(dataset: str) -> ClosedWorldModel:
    base = dataset.replace("_noise10", "")
    if base not in _models:
        _models[base] = ClosedWorldModel(ROOT / "ontology" / f"{base}.owl")
    return _models[base]


def scores(y, p) -> dict:
    tp = sum(a == 1 and b == 1 for a, b in zip(y, p))
    tn = sum(a == 0 and b == 0 for a, b in zip(y, p))
    fp = sum(a == 0 and b == 1 for a, b in zip(y, p))
    fn = sum(a == 1 and b == 0 for a, b in zip(y, p))
    return {"tp": tp, "tn": tn, "fp": fp, "fn": fn}


def run_one(s: dict, dataset: str, fold: str, train_ids, test_ids, labels) -> dict:
    pos = [i for i in train_ids if labels[i] == 1]
    neg = [i for i in train_ids if labels[i] == 0]
    conf_path = CONF / s["name"] / dataset / f"{fold}.conf"
    conf_path.parent.mkdir(parents=True, exist_ok=True)
    conf_path.write_text(make_conf(s, dataset, pos, neg, conf_path))

    run_dir = RUNS / s["name"] / dataset / fold
    run_dir.mkdir(parents=True, exist_ok=True)
    t0 = time.time()
    proc = subprocess.run([str(DLCLI), str(conf_path)], cwd=run_dir,
                          capture_output=True, text=True, timeout=s["time"] * 20 + 120)
    wall = time.time() - t0
    out = proc.stdout + proc.stderr
    (run_dir / "output.txt").write_text(out)
    parsed = parse_output(out)

    row = {"setting": s["name"], "dataset": dataset, "fold": fold,
           "n_train": len(train_ids), "n_test": len(test_ids),
           "wall_s": round(wall, 2), "tested": parsed["tested"],
           "concept": parsed["concept"], "concept_dl": None, "length": None, "depth": None,
           "train_acc": None}
    if parsed["concept"] is None:
        row["error"] = "no solution parsed (see %s)" % (run_dir / "output.txt")
        return row
    c = parse(parsed["concept"])
    m = model_for(dataset)
    row.update(concept_dl=to_dl(c), length=length(c), depth=depth(c))
    ptr = m.classify(c, train_ids)
    ytr = [labels[i] for i in train_ids]
    row["train_acc"] = round(sum(a == b for a, b in zip(ptr, ytr)) / len(ytr), 4)
    if test_ids:
        pte = m.classify(c, test_ids)
        row.update(scores([labels[i] for i in test_ids], pte))
        row["test_pred"] = " ".join(f"{i}:{p}" for i, p in zip(test_ids, pte))
    return row


FIELDS = ["setting", "dataset", "fold", "n_train", "n_test", "concept", "concept_dl",
          "length", "depth", "train_acc", "tp", "tn", "fp", "fn", "wall_s", "tested",
          "test_pred", "error"]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("settings", nargs="*", default=list(SETTINGS))
    ap.add_argument("--jobs", type=int, default=4)
    ap.add_argument("--datasets", nargs="*")
    args = ap.parse_args()

    jobs = []
    for name in args.settings:
        s = setting(name)
        for ds in s["datasets"]:
            if args.datasets and ds not in args.datasets:
                continue
            data = load_dataset(ds)
            labels = {t["id"]: t["label"] for t in data["trains"]}
            all_ids = list(labels)
            jobs.append((s, ds, "full", all_ids, [], labels))
            for k, f in enumerate(load_splits(ds)):
                jobs.append((s, ds, f"fold{k:02d}", f["train"], f["test"], labels))
    for ds in {j[1] for j in jobs}:  # load models before threading
        model_for(ds)
    print(f"{len(jobs)} DL-Learner runs, {args.jobs} in parallel")

    rows = []
    with ThreadPoolExecutor(args.jobs) as pool:
        futs = {pool.submit(run_one, *j): j for j in jobs}
        for n, fut in enumerate(as_completed(futs), 1):
            r = fut.result()
            rows.append(r)
            print(f"[{n}/{len(jobs)}] {r['setting']:18s} {r['dataset']:21s} {r['fold']:7s} "
                  f"{r['wall_s']:6.1f}s  {r.get('concept_dl') or r.get('error')}", flush=True)

    # merge with existing results (re-running a setting replaces its rows)
    out = RESULTS / "dl_runs.csv"
    old = []
    if out.exists():
        done = {(r["setting"], r["dataset"]) for r in rows}
        with out.open() as f:
            old = [r for r in csv.DictReader(f) if (r["setting"], r["dataset"]) not in done]
    allrows = sorted(old + rows, key=lambda r: (r["setting"], r["dataset"], r["fold"]))
    with out.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=FIELDS, extrasaction="ignore")
        w.writeheader()
        w.writerows(allrows)
    print(f"wrote {out} ({len(allrows)} rows)")


if __name__ == "__main__":
    main()
